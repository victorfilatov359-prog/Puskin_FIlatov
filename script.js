/* ===== ЛОГИКА МОДАЛЬНОГО ОКНА ===== */
const overlay = document.getElementById('modalOverlay');
const modalBody = document.getElementById('modalBody');
const closeBtn = document.getElementById('closeBtn');

function openModal(key) {
  const t = tales[key];
  if (!t) return;

  const metaHtml = t.meta.map(m => `<span>${m}</span>`).join('');
  const heroesHtml = t.heroes.map(h => `<li>${h}</li>`).join('');
  const factsHtml = t.facts.map(f => `<li>${f}</li>`).join('');

  modalBody.innerHTML = `
    <div class="m-icon">${t.icon}</div>
    <h2>${t.title}</h2>
    <div class="m-meta">${metaHtml}</div>

    <h4>Сюжет</h4>
    <p>${t.plot}</p>

    <h4>Герои</h4>
    <ul>${heroesHtml}</ul>

    <h4>Интересные факты</h4>
    <ul>${factsHtml}</ul>

    <div class="m-quote">${t.quote}</div>
  `;

  overlay.classList.add('active');
  document.body.classList.add('modal-open');
  document.getElementById('modalContent').scrollTop = 0;
}

function closeModal() {
  overlay.classList.remove('active');
  document.body.classList.remove('modal-open');
}

/* Клик по карточкам */
document.querySelectorAll('.card').forEach(card => {
  card.addEventListener('click', () => openModal(card.dataset.tale));
});

/* Закрытие */
closeBtn.addEventListener('click', closeModal);
overlay.addEventListener('click', e => {
  if (e.target === overlay) closeModal();
});
document.addEventListener('keydown', e => {
  if (e.key === 'Escape' && overlay.classList.contains('active')) closeModal();
});
